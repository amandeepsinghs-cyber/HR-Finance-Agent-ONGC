_CF_KEYS = {
    "CFO": r"(?i)^net cash.*operating activities",
    "CFI": r"(?i)^net cash.*investing activities",
    "CFF": r"(?i)^net cash.*financing activities",
    "NET": r"(?i)^net (increase|decrease|\(decrease\)|change).*cash",
}


@pytest.mark.parametrize("scope", ["standalone", "consolidated"])
def test_cf_completeness_every_ar(full, scope):
    rows, _, _ = full
    own = {"AR_FY2016-17": "FY17", "AR_FY2017-18": "FY18", "AR_FY2018-19": "FY19", "AR_FY2021-22": "FY22",
           "AR_FY2022-23": "FY23", "AR_FY2023-24": "FY24", "AR_FY2024-25": "FY25", "AR_FY2025-26": "FY26"}
    for v, fy in own.items():
        cf = [r for r in rows if r["report_vintage"] == v and r["scope"] == scope and r["statement"] == "cash_flow"]
        for key, rx in _CF_KEYS.items():
            for f in (fy, f"FY{int(fy[2:]) - 1:02d}"):
                r = _one(cf, rx, f)
                assert r["is_subtotal"] and r["subtotal_ok"], (v, scope, key, f, r["raw_label"])


