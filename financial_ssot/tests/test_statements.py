def _fixture_region(tag: str, page_nums: list[int], title_rx: str) -> list[tuple[int, int, str]]:
    """Region lines (line_no is 1-based within the fixture set) from exact page-text fixtures."""
    lines = []
    for pg in page_nums:
        for t in (FIX / f"{tag}_p{pg}.txt").read_text(encoding="utf-8").split("\n"):
            lines.append((len(lines) + 1, pg, t.rstrip("\r")))
    start = next(i for i, (_, _, t) in enumerate(lines) if re.search(title_rx, t))
    out = []
    for k, item in enumerate(lines[start:]):
        if k and any(rx.search(item[2]) for rx in st._END):
            break
        out.append(item)
    return out


def _fx_rows(tag, pages_, title_rx, statement):
    rows, issues = st.parse_region(_fixture_region(tag, pages_, title_rx), doc=f"{tag}.txt",
                                   report_vintage="fixture", scope="standalone", statement=statement,
                                   extracted_at="2026-10-23T00:00:00Z")
    return rows, issues


def _one(rows, label_rx, fy, period_type="annual"):
    hits = [r for r in rows if re.search(label_rx, r["raw_label"]) and r["fiscal_year"] == fy
            and r["period_type"] == period_type]
    assert len(hits) == 1, (label_rx, fy, [(h["raw_label"], h["raw_value_text"]) for h in hits])
    return hits[0]


