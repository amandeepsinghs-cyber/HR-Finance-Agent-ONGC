@pytest.mark.parametrize("vintage, fy", [
    ("AR_FY2016-17", "FY17"), ("AR_FY2017-18", "FY18"), ("AR_FY2018-19", "FY19"),
    ("AR_FY2021-22", "FY22"), ("AR_FY2022-23", "FY23"), ("AR_FY2023-24", "FY24"),
    ("AR_FY2024-25", "FY25"), ("AR_FY2025-26", "FY26"),
])
@pytest.mark.parametrize("scope", ["standalone", "consolidated"])
def test_identities_and_row_counts(full, vintage, fy, scope):
    rows, _, checks = full
    c = next(c for c in checks if c["report_vintage"] == vintage and c["scope"] == scope
             and c["fiscal_year"] == fy and c["period_type"] == "annual")
    assert c["pnl_chain_ok"] and c["bs_identity_ok"] and c["cash_tie_ok"], c
    mine = [r for r in rows if r["report_vintage"] == vintage and r["scope"] == scope and r["fiscal_year"] == fy
            and r["period_type"] == "annual"]
    tot = [r for r in mine if r["is_subtotal"] and r["unit"] == "INR_mn"]
    assert tot and all(r["subtotal_ok"] for r in tot), [r["raw_label"] for r in tot if not r["subtotal_ok"]]
    count = {s: sum(r["statement"] == s for r in mine) for s in st.STATEMENTS}
    # ONGC prints 26-27 P&L and 43-48 BS value lines (standalone); see evidence for the packet's 30/60 target
    assert count["pnl"] >= 26 and count["balance_sheet"] >= 43 and count["cash_flow"] >= 40, count


