def write_yaml(filename, data):
    """Write YAML data cleanly formatted with UTF-8."""
    target = REF_DIR / filename
    with open(target, "w", encoding="utf-8") as f:
        yaml.dump(data, f, sort_keys=False, allow_unicode=True, width=120)
    print(f"Generated {filename}: {len(data) if isinstance(data, list) else len(data.keys())} top-level items")


