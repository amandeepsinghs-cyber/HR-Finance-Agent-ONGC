"""P4.6 (SPEC-10 §4.3, §6 AC 3, BUG-24): WeasyPrint PDF export verification using `pdffonts`, `pdftotext`, and `pdfimages`.

Verifies:
1. `pdffonts` lists `NotoSans` and `NotoSansDevanagari` as embedded (`emb yes`).
2. `pdftotext` output contains `₹`, `राजस्व` (and Hindi title) with **0** occurrences of `■`.
3. Table header repeats on page 2 for a 60+ row roster (`pdftotext -f 2 -l 2`).
4. Chart image is embedded when `chart_png` is supplied (`pdfimages -list` >= 1 image),
   and when omitted on a chart visual, the note `"Chart image not included; download PNG from the card."` appears.
5. Aggregate export includes `"Aggregate view (access level: E2_HR)"` banner and footer `"Generated by Yukti"`.
"""

from __future__ import annotations

import base64
import io
import json
from pathlib import Path
import subprocess
import sys

from PIL import Image
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.export_audit import enforce_export_rbac
from app.tools.export_tool import DocumentExporter

FIXTURES_DIR = Path(__file__).resolve().parent.parent.parent / "contracts" / "fixtures" / "export"


@pytest.fixture()
def exporter(tmp_path: Path) -> DocumentExporter:
    return DocumentExporter(exports_dir=tmp_path / "exports")


def _load_fixture(name: str) -> dict:
    return json.loads((FIXTURES_DIR / name).read_text(encoding="utf-8"))


def _make_sample_chart_png_data_url(width: int = 400, height: int = 200) -> str:
    buf = io.BytesIO()
    img = Image.new("RGB", (width, height), color=(128, 0, 0))
    img.save(buf, format="PNG")
    b64 = base64.b64encode(buf.getvalue()).decode("ascii")
    return f"data:image/png;base64,{b64}"


def _parse_embedded_fonts(pdf_path: Path) -> list[tuple[str, str]]:
    """Returns `[(font_name, emb_flag), ...]` from `pdffonts`."""
    out = subprocess.check_output(["pdffonts", str(pdf_path)], text=True)
    results = []
    for line in out.splitlines()[2:]:
        parts = line.split()
        if len(parts) >= 5:
            font_name = parts[0]
            # Find 'yes'/'no' columns (emb, sub, uni)
            yn = [p for p in parts if p in ("yes", "no")]
            if yn:
                results.append((font_name, yn[0]))
    return results


def test_hindi_pdf_embeds_noto_fonts_and_renders_rupee_and_devanagari_with_zero_tofu(
    exporter: DocumentExporter,
) -> None:
    contract = _load_fixture("hindi_revenue_pat_synthetic.json")
    pdf_path = exporter.export_pdf(filename="yukti_hindi_rev.pdf", contract=contract, persona="CMD")

    fonts = _parse_embedded_fonts(pdf_path)
    assert any("NotoSans" in name and "Devanagari" not in name and emb == "yes" for name, emb in fonts), fonts
    assert any("NotoSansDevanagari" in name and emb == "yes" for name, emb in fonts), fonts

    text = subprocess.check_output(["pdftotext", str(pdf_path), "-"], text=True)
    assert "₹" in text
    assert "राजस्व" in text
    assert "शुद्ध लाभ" in text
    assert text.count("■") == 0
    assert text.count("\ufffd") == 0
    assert "Generated by Yukti" in text
    assert "Illustrative" in text


def test_roster_65_rows_repeats_table_header_on_page_2_and_embeds_chart_png(
    exporter: DocumentExporter,
) -> None:
    contract = _load_fixture("v19_delhi_roster_synthetic.json")
    chart_png = _make_sample_chart_png_data_url()
    pdf_path = exporter.export_pdf(
        filename="yukti_v19_roster.pdf",
        contract=contract,
        chart_png=chart_png,
        persona="CMD",
    )

    # 1. Fonts embedded
    fonts = _parse_embedded_fonts(pdf_path)
    assert any("NotoSans" in name and emb == "yes" for name, emb in fonts), fonts
    assert any("NotoSansDevanagari" in name and emb == "yes" for name, emb in fonts), fonts

    # 2. Chart image present via pdfimages -list
    img_list = subprocess.check_output(["pdfimages", "-list", str(pdf_path)], text=True)
    img_lines = [ln for ln in img_list.splitlines()[2:] if ln.strip()]
    assert len(img_lines) >= 1, img_list

    # 3. Table header repeats on page 1 and page 2
    page1 = subprocess.check_output(["pdftotext", "-f", "1", "-l", "1", str(pdf_path), "-"], text=True)
    page2 = subprocess.check_output(["pdftotext", "-f", "2", "-l", "2", str(pdf_path), "-"], text=True)
    p1_norm = " ".join(page1.split())
    p2_norm = " ".join(page2.split())
    for hdr in ("Name", "Designation", "Level", "Tenure in Delhi (yrs)"):
        assert hdr in p1_norm, f"Missing {hdr} on page 1"
        assert hdr in p2_norm, f"Missing {hdr} on page 2"
    assert (page1 + page2).count("■") == 0


def test_pnl_statement_pdf_and_missing_chart_note_and_aggregate_banner(
    exporter: DocumentExporter,
) -> None:
    pnl = _load_fixture("pnl_statement_fy22_fy26_synthetic.json")
    pnl_pdf = exporter.export_pdf(filename="yukti_pnl.pdf", contract=pnl, persona="CMD")
    pnl_text = subprocess.check_output(["pdftotext", str(pnl_pdf), "-"], text=True)
    pnl_norm = " ".join(pnl_text.split())
    assert "Statement of Profit and Loss" in pnl_norm
    assert "Revenue from operations" in pnl_norm
    assert "Profit before tax" in pnl_norm
    assert "Profit for the year (PAT)" in pnl_norm
    assert "132,508.14" in pnl_norm
    assert pnl_text.count("■") == 0

    # Chart visual without chart_png -> includes note "Chart image not included; download PNG from the card."
    chart_contract = {
        "turn_id": "turn_chart_only",
        "visual": {
            "type": "chart",
            "title": "Revenue Trend (₹ Crore)",
            "chart": {"kind": "line", "data": [{"fy": "FY26", "rev": 132508}]},
        },
    }
    chart_pdf = exporter.export_pdf(filename="yukti_chart_no_png.pdf", contract=chart_contract, persona="CMD")
    chart_txt = subprocess.check_output(["pdftotext", str(chart_pdf), "-"], text=True)
    assert "Chart image not included; download PNG from the card." in chart_txt

    # Aggregate E2_HR export -> banner "Aggregate view (access level: E2_HR)"
    v19 = _load_fixture("v19_delhi_roster_synthetic.json")
    masked_c, masked_flag, is_agg, _, _ = enforce_export_rbac(v19, "E2_HR")
    agg_pdf = exporter.export_pdf(
        filename="yukti_v19_agg.pdf",
        contract=masked_c,
        persona="E2_HR",
        masked=masked_flag,
        is_aggregate=is_agg,
    )
    agg_txt = subprocess.check_output(["pdftotext", str(agg_pdf), "-"], text=True)
    assert "Aggregate view (access level: E2_HR)" in agg_txt
    assert "Officer 1" not in agg_txt
