        row["pat_margin_pct"] = round(100.0 * row["pat_inr_cr"] / row["gross_revenue_inr_cr"], 2)
        row["effective_tax_rate_pct"] = round(100.0 * row["tax_expense_total_inr_cr"] / row["pbt_inr_cr"], 2) if row["pbt_inr_cr"] else 0.0

