        row["net_revenue_inr_cr"] = round(row["gross_revenue_inr_cr"] - row["statutory_levies_total_inr_cr"], 2)
        row["operating_expenses_total_inr_cr"] = round(
            row["prod_transport_selling_exp_inr_cr"] + row["employee_benefit_net_pnl_inr_cr"] + row["other_expenses_inr_cr"], 2
        )
        row["ebitda_inr_cr"] = round(
            row["gross_revenue_inr_cr"] - row["statutory_levies_total_inr_cr"] - row["operating_expenses_total_inr_cr"], 2
        )
        row["ebitda_margin_pct"] = round(100.0 * row["ebitda_inr_cr"] / row["gross_revenue_inr_cr"], 2)
